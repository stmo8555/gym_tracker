CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    pwd TEXT NOT NULL
);

CREATE TABLE programs (
    id INT GENERATED by DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    active BOOLEAN DEFAULT FALSE,
    day INT DEFAULT 0,
    rotation_pos INT DEFAULT 0,
    rotations INT NULL,
    deload_interval INT NULL,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX one_active_program_per_user
    ON programs (user_id)
    WHERE active;


CREATE TABLE workouts (
    id INT GENERATED by DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE
);

--figure out how we should handle sets and history
CREATE TABLE exercises (
    id INT GENERATED by DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    rep_range_lower INT NOT NULL,
    rep_range_upper INT NOT NULL,
    sets INT NOT NULL,
    rest_seconds INT DEFAULT 0,
    note TEXT NULL,
    position INT NOT NULL,
    workout_id INT NOT NULL REFERENCES workouts(id) ON DELETE CASCADE,
    UNIQUE (workout_id, position)
);

-- workout_id NULL = rest day. RESTRICT so deleting a workout can't silently
-- turn the days that use it into rest days.
CREATE TABLE program_days (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id INT NOT NULL REFERENCES programs(id) ON DELETE CASCADE,
    day_order INT NOT NULL,
    workout_id INT NULL REFERENCES workouts(id) ON DELETE RESTRICT,
    UNIQUE (program_id, day_order)
);

-- finished_at NULL = in progress
CREATE TABLE workout_sessions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    program_id INT NULL REFERENCES programs(id) ON DELETE SET NULL,
    workout_id INT NULL REFERENCES workouts(id) ON DELETE SET NULL,
    day_order INT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ NULL
);

CREATE UNIQUE INDEX one_in_progress_session_per_user
    ON workout_sessions (user_id)
    WHERE finished_at IS NULL;

-- one row per performed set
CREATE TABLE workout_sessions_sets (
    id INT GENERATED by DEFAULT AS IDENTITY PRIMARY KEY,
    workout_sessions_id INT NOT NULL REFERENCES workout_sessions(id) ON DELETE CASCADE,
    exercise_id INT NULL REFERENCES exercises(id) ON DELETE SET NULL,
    exercise_name TEXT NOT NULL,
    set_number INT NOT NULL,
    reps INT NULL,
    weight NUMERIC(6, 2) NULL,
    note TEXT NULL,
    finished_at TIMESTAMPTZ NULL
);
